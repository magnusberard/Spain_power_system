"""
Gate-volume validation — what each market gate moves, model vs OMIE, at any horizon.

This is the measurement layer every market-chain extension is judged against.
It runs in two modes:

    python plotting/gate_volume_validation.py <results>            single run
    python plotting/gate_volume_validation.py <before> <after>     A/B comparison

The A/B mode is the one that validates a change: it reports the same metrics for
two runs side by side with the delta, so "did this extension do anything" has a
number rather than an impression.

What it measures
----------------
  1. NET position change per technology per gate, against the observed OMIE
     sessions.  The only quantity comparable between the model and the Spanish
     market, and therefore the calibration target.
  2. GROSS movement and the reshuffling index (gross ÷ net system change).
     Separates netting a forecast error from reshuffling the merit order.
  3. Cleared price level and intraday spread per gate, against observed.
  4. Generation-mix NRMSE against the OMIE cleared programme.
  5. Reservoir-hydro energy per day, against the mid-term schedule's budget.

Why gross volume is NOT the calibration target
----------------------------------------------
Hagemann & Weber (2015, pp. 18 and 24) show observed Iberian intraday volume
exceeds the fundamental ("competitive") benchmark by a factor of six, because
Spanish rules route a firm's rescheduling between its OWN plants through the
intraday exchange.  This model has no firms, so that component of real volume
has no counterpart here.  Koks et al. (2026, p. 8) confirm PowerVision's Active
case IS that competitive benchmark.  Matching gross volume to OMIE would fit a
number generated by a mechanism the model does not contain.  Report gross as a
diagnostic; calibrate on net.

Scalability
-----------
The chain currently runs two days but is intended for a sampled multi-week
horizon, so nothing here may assume the two 2024 study days:

  * **Dates are discovered from the results**, never hardcoded.  Reference data
    is joined only for those days that have it (currently the two 2024 days),
    and model-side metrics are reported for every day found.
  * **The dispatch CSVs are streamed, not loaded.**  A gate carries ~2 340 unit
    rows per hour — 112 k rows for two days, but ~20 M rows and ~880 MB per
    gate over a full year, times five gates.  `pd.read_csv` on whole files does
    not survive that.  Each file is read in chunks and aggregated to
    (date, hour, category) on the way in, which collapses a year to ~96 k rows
    per gate regardless of fleet size.  This is why `load_chain` from
    `paper_figures_2024` is deliberately NOT reused — only its category
    vocabulary and its pure metric functions are.
  * **Per-day tables collapse to summaries** past a handful of days; the full
    per-day detail always goes to CSV.

Known comparison caveats, deliberately not papered over
-------------------------------------------------------
* The reference file's rows do NOT sum to zero: the `*_tot` columns leave a
  residual of -204, -364, -69 and -6 MW across the four day/session
  combinations.  A matched market should net out, so either a category is
  missing or the `Load` row's sign convention differs from the generation rows.
  **Confirm the file's provenance against OMIE's published reports before any
  number here becomes load-bearing.**
* The model has no IDA1, but Spain has run IDA1/IDA2/IDA3 since 14 June 2024,
  so the model's DA→ID2 step absorbs what the real market split over two
  sessions.  The ID3 comparison is the cleaner one.
* ID3 trades only delivery hours 12–23; both sides average over 24 hours with
  zeros elsewhere, so the means stay comparable.
* Gate deltas apply the XB import clipping from `_categorise`.  Reading the
  dispatch CSVs raw instead makes the border exchange look like fresh
  rescheduling — that error inflated DA→ID2 movement from 1.19 % to 5.68 % of
  demand on the 2035 runs.
"""

