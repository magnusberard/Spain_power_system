def main(argv):
    out_dir = Path(FIG_DIR)
    ref = load_reference()
    if len(argv) >= 2:
        a, b = load_run(argv[0]), load_run(argv[1])
        for r in (a, b):
            if not r["gates"]:
                raise SystemExit(f"No *_dispatch.csv in {r['path']}")
        report_ab(a, b, ref, out_dir)
        return
    run = load_run(argv[0] if argv else RESULTS)
    if not run["gates"]:
        raise SystemExit(f"No *_dispatch.csv in {run['path']} — run the chain first.")
    print(f"Reading model results from : {run['path']}")
    print(f"Gates found                : {', '.join(sorted(run['gates']))}")
    print(f"Days found                 : {len(run['days'])}")
    report_single(run, ref, out_dir)


if __name__ == "__main__":
    main(sys.argv[1:])
